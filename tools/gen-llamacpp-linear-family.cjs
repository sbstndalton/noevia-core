'use strict';
// Generate generic private-IR templates. No estimator/business source is read.
// All operator/template combinations are emitted independently of callers.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const output = path.join(__dirname, '../server/llamacpp-autoconfig-linear-family.cjs');
if (process.argv.length > 3 || process.argv[2] && process.argv[2] !== '--check') {
  console.error('usage: node tools/gen-llamacpp-linear-family.cjs [--check]');
  process.exit(2);
}
const operators = ['+', '-', '*', '/', '%', '**', '>', '>=', '<', '<=', '===', '!==', '==', '!='];
const atom = i => '(tag' + i + '===0?a:tag' + i + '===1?b:tag' + i + '===2?c:tag' + i + '===3?data' + i + ':tag' + i + '===4?undefined:environment[data' + i + '])';
const parts = [
  "'use strict';\n",
  '// Generated by tools/gen-llamacpp-linear-family.cjs; use --check to verify.\n',
  '// Generic operators and private IR shapes only. Live binding/property reads remain ordered.\n',
];
const entries = [];
function factory(shape, root, rootIndex, inner, innerIndex) {
  const name = shape + '_' + rootIndex + (innerIndex === undefined ? '' : '_' + innerIndex);
  const key = shape + ':' + rootIndex + (innerIndex === undefined ? '' : ':' + innerIndex);
  const length = shape === 'S' ? 2 : 4;
  parts.push('function ' + name + '(environment,atoms){\n');
  for (let i = 0; i < length; i++) parts.push('const tag' + i + '=atoms[' + i + '][0],data' + i + '=atoms[' + i + '][1];\n');
  parts.push('return (a,b,c)=>{\n');
  if (shape === 'A') {
    parts.push('const left=' + atom(0) + ';\nconst object=' + atom(1) + ';\nconst keyLeft=' + atom(2) + ';\nconst keyRight=' + atom(3) + ';\nconst key=keyLeft ' + inner + ' keyRight;\nconst right=object[key];\nreturn left ' + root + ' right;\n');
  } else if (shape === 'M') {
    parts.push('const object=' + atom(0) + ';\nconst keyLeft=' + atom(1) + ';\nconst keyRight=' + atom(2) + ';\nconst key=keyLeft ' + inner + ' keyRight;\nconst left=object[key];\nconst right=' + atom(3) + ';\nreturn left ' + root + ' right;\n');
  } else if (shape === 'B') {
    parts.push('const leftObject=' + atom(0) + ';\nconst leftKey=' + atom(1) + ';\nconst left=leftObject[leftKey];\nconst rightObject=' + atom(2) + ';\nconst rightKey=' + atom(3) + ';\nconst right=rightObject[rightKey];\nreturn left ' + root + ' right;\n');
  } else {
    parts.push('const left=' + atom(0) + ';\nconst right=' + atom(1) + ';\nreturn left ' + root + ' right;\n');
  }
  parts.push('};\n}\n');
  entries.push(JSON.stringify(key) + ':' + name);
}
for (let root = 0; root < operators.length; root++) {
  for (let inner = 0; inner < operators.length; inner++) {
    factory('A', operators[root], root, operators[inner], inner);
    factory('M', operators[root], root, operators[inner], inner);
  }
  factory('B', operators[root], root);
  factory('S', operators[root], root);
}
parts.push('const factories={__proto__:null,' + entries.join(',') + '};\n');
parts.push('const operators={__proto__:null,' + operators.map((op, index) => JSON.stringify(op) + ':' + index).join(',') + '};\n');
parts.push([
  '// Trees are private Rust JSON IR; atom values and caller objects are never inspected.',
  'function node(tree,length){return tree!==null&&typeof tree===\'object\'&&tree.length===length;}',
  'function atom(tree){',
  ' if(node(tree,2)&&tree[0]===\'arg\'&&(tree[1]===0||tree[1]===1||tree[1]===2))return [tree[1],undefined];',
  ' if(node(tree,2)&&tree[0]===\'literal\')return [3,tree[1]];',
  ' if(node(tree,1)&&tree[0]===\'undefined\')return [4,undefined];',
  ' if(node(tree,2)&&tree[0]===\'load\'&&typeof tree[1]===\'string\')return [5,tree[1]];',
  ' return null;',
  '}',
  'function binary(tree){return node(tree,4)&&tree[0]===\'binary\'&&typeof tree[1]===\'string\'&&operators[tree[1]]!==undefined;}',
  'function get(tree){return node(tree,3)&&tree[0]===\'get\'&&atom(tree[1])&&atom(tree[2]);}',
  'function computed(tree){return node(tree,3)&&tree[0]===\'get\'&&atom(tree[1])&&binary(tree[2])&&atom(tree[2][2])&&atom(tree[2][3]);}',
  'function build(tree,environment){',
  ' if(!binary(tree))return null;',
  ' const root=operators[tree[1]],left=tree[2],right=tree[3];',
  ' if(atom(left)&&computed(right))return factories[\'A:\'+root+\':\'+operators[right[2][1]]](environment,[atom(left),atom(right[1]),atom(right[2][2]),atom(right[2][3])]);',
  ' if(computed(left)&&atom(right))return factories[\'M:\'+root+\':\'+operators[left[2][1]]](environment,[atom(left[1]),atom(left[2][2]),atom(left[2][3]),atom(right)]);',
  ' if(get(left)&&get(right))return factories[\'B:\'+root](environment,[atom(left[1]),atom(left[2]),atom(right[1]),atom(right[2])]);',
  ' if(atom(left)&&atom(right))return factories[\'S:\'+root](environment,[atom(left),atom(right)]);',
  ' return null;',
  '}',
  'module.exports={build};',
  '',
].join('\n'));
const text = parts.join('');
if (process.argv[2] === '--check') {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== text) {
    console.error('generated llama.cpp linear family is out of date');
    process.exit(1);
  }
} else fs.writeFileSync(output, text);
console.log(JSON.stringify({ output, bytes: Buffer.byteLength(text), sha256: crypto.createHash('sha256').update(text).digest('hex'), check: process.argv[2] === '--check' }));
